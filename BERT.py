#### Main ####
##############

def main():
    # Added seed for reproducability
    set_seed()

    # Make sure CUDA is enabled, otherwise takes too long
    print(f"Using device: {DEVICE}")
    if torch.cuda.is_available():
        print(f"GPU: {torch.cuda.get_device_name(0)}")

    # Diagnostic print check, program was getting stuck on loading data 
    # Had ChatGPT add progress bars and more diagnostic prints to see progress and where it was getting stuck, also added flush=True to make sure prints show up in correct order
    print("\nLoading training data...")
    train_df = load_dataset(TRAIN_FILE)

    # General structure taken from BERT example, and modified to fit our use case

    train_df = make_balanced_subset(train_df, MAX_TRAIN_EXAMPLES)

    train_texts = train_df[TEXT_COL].tolist()
    train_labels = convert_labels_to_binary(train_df[LABEL_COL]).tolist()

    print(f"Training examples: {len(train_texts)}")
    print(f"Positive class count: {sum(train_labels)}")
    print(f"Negative class count: {len(train_labels) - sum(train_labels)}")

    tokenizer = BertTokenizer.from_pretrained(MODEL_NAME)

    train_dataset = SarcasmDataset(
        train_texts,
        train_labels,
        tokenizer,
        MAX_LEN
    )

    train_loader = make_dataloader(
        train_dataset,
        batch_size=TRAIN_BATCH_SIZE,
        shuffle=True
    )

    print("\nLoading validation data...", flush=True)
    validation_df = load_dataset(VALIDATION_FILE)

    validation_texts = validation_df[TEXT_COL].tolist()
    validation_labels = convert_labels_to_binary(validation_df[LABEL_COL]).tolist()

    validation_dataset = SarcasmDataset(
        validation_texts,
        validation_labels,
        tokenizer,
        MAX_LEN
    )

    validation_loader = make_dataloader(
        validation_dataset,
        batch_size=EVAL_BATCH_SIZE,
        shuffle=False
    )

    model = BertForSequenceClassification.from_pretrained(
        MODEL_NAME,
        num_labels=2
    )

    model.to(DEVICE)

    # AdamW seems to work best for BERT
    optimizer = AdamW(
        model.parameters(),
        lr=LEARNING_RATE,
        weight_decay=WEIGHT_DECAY
    )

    total_steps = len(train_loader) * EPOCHS

    scheduler = get_linear_schedule_with_warmup(
        optimizer,
        num_warmup_steps=0,
        num_training_steps=total_steps
    )

    scaler = torch.amp.GradScaler("cuda", enabled=torch.cuda.is_available())
    best_validation_f1 = 0.0
    best_epoch = 0

    print("\nTraining BERT...", flush=True)

    for epoch in range(EPOCHS):
        avg_train_loss = train_one_epoch(
            model,
            train_loader,
            optimizer,
            scheduler,
            DEVICE,
            scaler
        )

        print(f"\nEpoch {epoch + 1}/{EPOCHS}", flush=True)
        print(f"Train Loss: {avg_train_loss:.4f}", flush=True)

        validation_results = evaluate_model(
            model,
            validation_loader,
            DEVICE,
            dataset_name=f"validation_epoch_{epoch + 1}"
        )

        validation_f1 = validation_results["f1"]

        if validation_f1 > best_validation_f1:
            best_validation_f1 = validation_f1
            best_epoch = epoch + 1

            os.makedirs("bert_best_model", exist_ok=True)
            model.save_pretrained("bert_best_model")
            tokenizer.save_pretrained("bert_best_model")

            print(
                f"New best model saved from epoch {best_epoch} "
                f"with validation F1 = {best_validation_f1:.4f}",
                flush=True
            )

    print(
        f"\nBest validation epoch: {best_epoch} "
        f"with F1 = {best_validation_f1:.4f}",
        flush=True
    )

    os.makedirs("bert_model_output", exist_ok=True)
    model.save_pretrained("bert_model_output")
    tokenizer.save_pretrained("bert_model_output")

    all_results = []
    print("\nLoading best validation model for final testing...", flush=True)

    model = BertForSequenceClassification.from_pretrained("bert_best_model")
    model.to(DEVICE)

    for dataset_name, path in TEST_FILES.items():
        print(f"\nLoading test set: {dataset_name} from {path}")
        test_df = load_dataset(path)

        test_texts = test_df[TEXT_COL].tolist()
        test_labels = convert_labels_to_binary(test_df[LABEL_COL]).tolist()

        test_dataset = SarcasmDataset(
            test_texts,
            test_labels,
            tokenizer,
            MAX_LEN
        )

        test_loader = make_dataloader(
            test_dataset,
            batch_size=EVAL_BATCH_SIZE,
            shuffle=False
        )

        results = evaluate_model(
            model,
            test_loader,
            DEVICE,
            dataset_name
        )

        all_results.append(results)

    results_df = pd.DataFrame(all_results)

    print("\n" + "=" * 70)
    print("Summary of results")
    print("=" * 70)
    print(results_df.to_string(index=False))

    results_df.to_csv(RESULTS_FILE, index=False)
    print(f"\nSaved summary to {RESULTS_FILE}")


if __name__ == "__main__":
    main()