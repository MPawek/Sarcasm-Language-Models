from torch.utils.data import Dataset, DataLoader
from torch.optim import AdamW

from transformers import (
    BertTokenizer,
    BertForSequenceClassification,
    get_linear_schedule_with_warmup
)

from sklearn.metrics import (
    accuracy_score,
    precision_score,
    recall_score,
    f1_score,
    roc_auc_score,
    average_precision_score,
    confusion_matrix,
    classification_report
)

#########################
#### Data Locations #####
#########################

TRAIN_FILE = "train_processed_clean.csv"
VALIDATION_FILE = "validation_processed_clean.csv"

TEST_FILES = {
    "clean": "twitter_processed_clean.csv",
    "lowercase": "twitter_processed_lowercase.csv",
    "no_punctuation": "twitter_processed_nopunct.csv",
    "lowercase_no_punctuation": "twitter_processed_lower_nopunct.csv"
}

TEXT_COL = "processed_text"
LABEL_COL = "label"
POSITIVE_LABELS = {1}

MODEL_NAME = "bert-base-uncased"

#########################
#### Hyperparameters ####
#########################

# Current best settings (as of 5/9):
MAX_LEN = 96
TRAIN_BATCH_SIZE = 32
EVAL_BATCH_SIZE = 64
EPOCHS = 3
LEARNING_RATE = 1e-5
WEIGHT_DECAY = 0.0001
RANDOM_SEED = 42

# Set to None to use full training set
MAX_TRAIN_EXAMPLES = None

# Windows has trouble with multiprocessing, so leave at 0
NUM_WORKERS = 0

# Make sure CUDA settings work, otherwise takes too long
DEVICE = torch.device("cuda" if torch.cuda.is_available() else "cpu")
RESULTS_FILE = "bert_results_summary.csv"

if torch.cuda.is_available():
    torch.backends.cudnn.benchmark = True
    torch.set_float32_matmul_precision("high")


###############################################
#### Added seed for better reproducability ####
###############################################

def set_seed(seed=RANDOM_SEED):
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)

    if torch.cuda.is_available():
        torch.cuda.manual_seed_all(seed)


###################################################
#### LABEL / DATA HELPERS generated by ChatGPT ####
###################################################

def convert_labels_to_binary(series):
    return series.apply(lambda x: 1 if x in POSITIVE_LABELS else 0)


def load_dataset(path, text_col=TEXT_COL, label_col=LABEL_COL):
    df = pd.read_csv(path)

    if text_col not in df.columns:
        raise ValueError(
            f"Missing text column '{text_col}' in {path}. "
            f"Found columns: {df.columns.tolist()}"
        )

    if label_col not in df.columns:
        raise ValueError(
            f"Missing label column '{label_col}' in {path}. "
            f"Found columns: {df.columns.tolist()}"
        )

    df = df.dropna(subset=[text_col, label_col]).copy()
    df[text_col] = df[text_col].astype(str)

    return df


def make_balanced_subset(df, max_examples):
    if max_examples is None or len(df) <= max_examples:
        return df

    # Separate classes explicitly (safer than groupby)
    df_pos = df[df[LABEL_COL] == 1]
    df_neg = df[df[LABEL_COL] == 0]

    n = max_examples // 2

    df_pos_sample = df_pos.sample(n=min(len(df_pos), n), random_state=RANDOM_SEED)
    df_neg_sample = df_neg.sample(n=min(len(df_neg), n), random_state=RANDOM_SEED)

    subset = pd.concat([df_pos_sample, df_neg_sample])
    subset = subset.sample(frac=1, random_state=RANDOM_SEED).reset_index(drop=True)

    return subset


