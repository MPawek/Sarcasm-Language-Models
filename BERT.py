#### Training loop ####
#######################
# Taken from BERT example, modified for our use case 
# Had ChatGPT add progress bars to see progress

# Single epoch training loop, returns average loss for the epoch
def train_one_epoch(model, dataloader, optimizer, scheduler, device, scaler):
    model.train()
    total_loss = 0.0

    # MAKE SURE CUDA IS ENABLED IT TAKES SO LONG
    use_amp = torch.cuda.is_available()

    # tqdm progress bar for training loop
    for batch in tqdm(dataloader, desc="Training", leave=True):
        input_ids = batch["input_ids"].to(device, non_blocking=True)
        attention_mask = batch["attention_mask"].to(device, non_blocking=True)
        labels = batch["labels"].to(device, non_blocking=True)

        optimizer.zero_grad(set_to_none=True)

        with torch.amp.autocast(device_type="cuda", enabled=use_amp):
            outputs = model(
                input_ids=input_ids,
                attention_mask=attention_mask,
                labels=labels
            )
            loss = outputs.loss

        if use_amp:
            scaler.scale(loss).backward()
            scaler.step(optimizer)
            scaler.update()
        else:
            loss.backward()
            optimizer.step()

        scheduler.step()
        total_loss += loss.item()

    return total_loss / len(dataloader)


####################
#### Evaluation ####
####################

def evaluate_model(model, dataloader, device, dataset_name="dataset"):
    model.eval()

    all_labels = []
    all_preds = []
    all_probs = []

    # MAKE SURE CUDA IS ENABLED IT TAKES SO LONG
    use_amp = torch.cuda.is_available()

    with torch.no_grad():
        # tqdm progress bar for evaluation loop
        for batch in tqdm(dataloader, desc="Evaluating", leave=True):
            input_ids = batch["input_ids"].to(device, non_blocking=True)
            attention_mask = batch["attention_mask"].to(device, non_blocking=True)
            labels = batch["labels"].to(device, non_blocking=True)

            with torch.amp.autocast(device_type="cuda", enabled=use_amp):
                outputs = model(
                    input_ids=input_ids,
                    attention_mask=attention_mask
                )

            logits = outputs.logits
            probs = torch.softmax(logits, dim=1)[:, 1]
            preds = torch.argmax(logits, dim=1)

            all_labels.extend(labels.cpu().numpy())
            all_preds.extend(preds.cpu().numpy())
            all_probs.extend(probs.cpu().numpy())

    acc = accuracy_score(all_labels, all_preds)
    prec = precision_score(all_labels, all_preds, zero_division=0)
    rec = recall_score(all_labels, all_preds, zero_division=0)
    f1 = f1_score(all_labels, all_preds, zero_division=0)

    # Data formatted strange, had random column named "nan" that was causing errors, so added try/except to handle cases where only one class is present
    try:
        roc = roc_auc_score(all_labels, all_probs)
    except ValueError:
        roc = float("nan")

    try:
        pr_auc = average_precision_score(all_labels, all_probs)
    except ValueError:
        pr_auc = float("nan")

    cm = confusion_matrix(all_labels, all_preds)

    # Formatting done by ChatGPT to make results and graph more readable
    print("\n" + "=" * 70)
    print(f"Evaluation on: {dataset_name}")
    print("=" * 70)
    print(f"Accuracy     : {acc:.4f}")
    print(f"Precision    : {prec:.4f}")
    print(f"Recall       : {rec:.4f}")
    print(f"F1 Score     : {f1:.4f}")
    print(f"ROC AUC      : {roc:.4f}" if not np.isnan(roc) else "ROC AUC      : undefined")
    print(f"PR AUC       : {pr_auc:.4f}" if not np.isnan(pr_auc) else "PR AUC       : undefined")
    print("Confusion Matrix:")
    print(cm)
    print("\nClassification Report:")
    print(classification_report(all_labels, all_preds, zero_division=0))

    return {
        "dataset": dataset_name,
        "accuracy": acc,
        "precision": prec,
        "recall": rec,
        "f1": f1,
        "roc_auc": roc,
        "pr_auc": pr_auc
    }


